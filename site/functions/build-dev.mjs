// site/functions/build-dev.mjs - Writes dev-router.js, dev.neon1.tech's one CloudFront Function: the
// site and portal routers (handlers renamed) behind dev-gate.js. Comment lines and blank lines are
// dropped so the result stays under CloudFront's 10 KB function limit.
// Usage: node site/functions/build-dev.mjs [--check]   (make dev-router / make test)

import { readFileSync, writeFileSync } from "node:fs";

const here = (name) => new URL(`./${name}`, import.meta.url);
const LIMIT = 10240;

// One source file without its imports, comment lines, or blank lines, with its handler renamed
function part(name, rename) {
  let code = readFileSync(here(name), "utf8")
    .split("\n")
    .filter((l) => !/^\s*(\/\/.*)?$/.test(l) && !/^import /.test(l))
    .join("\n");
  if (rename) {
    if (!code.includes("function handler(event)")) throw new Error(`${name}: no handler to rename`);
    code = code.replace("function handler(event)", `function ${rename}(event)`);
  }
  return code;
}

// Top-level functions a later part declares again (query, redirect) are dropped from it: the copies
// match, and a module can't declare one name twice
function dedupe(code, seen) {
  const kept = [];
  let skipping = false;
  for (const line of code.split("\n")) {
    const m = /^(?:async )?function (\w+)\(/.exec(line);
    if (m && seen.has(m[1])) skipping = true;
    else if (m) seen.add(m[1]);
    if (!skipping) kept.push(line);
    if (skipping && line === "}") skipping = false;
  }
  return kept.join("\n");
}

const seen = new Set();
const out = [
  "// GENERATED by site/functions/build-dev.mjs from site-router.js, portal-router.js, and dev-gate.js. Do not edit.",
  "import cf from 'cloudfront';",
  "import crypto from 'crypto';",
  dedupe(part("site-router.js", "siteHandler"), seen),
  dedupe(part("portal-router.js", "portalHandler"), seen),
  dedupe(part("dev-gate.js"), seen),
  "",
].join("\n");

const size = Buffer.byteLength(out);
if (size > LIMIT) throw new Error(`dev-router.js would be ${size} bytes, over CloudFront's ${LIMIT}`);

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(here("dev-router.js"), "utf8"); } catch {}
  if (current !== out) { console.error("dev-router.js is stale: run make dev-router"); process.exit(1); }
  console.log(`dev-router.js is current (${size} bytes)`);
} else {
  writeFileSync(here("dev-router.js"), out);
  console.log(`wrote dev-router.js (${size} bytes)`);
}
